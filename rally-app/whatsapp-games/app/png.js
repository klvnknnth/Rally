/* Minimal zero-dependency PNG encoder (truecolor RGBA, filter 0).
 * Exports: encodePNG(width, height, rgbaBuffer) -> Buffer
 */
const zlib = require('zlib');

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const out = Buffer.alloc(8 + data.length + 4);
  out.writeUInt32BE(data.length, 0);
  out.write(type, 4, 'ascii');
  data.copy(out, 8);
  out.writeUInt32BE(crc32(out.subarray(4, 8 + data.length)), 8 + data.length);
  return out;
}

function encodePNG(width, height, rgba) {
  const raw = Buffer.alloc(height * (1 + width * 4));
  for (let y = 0; y < height; y++) {
    raw[y * (1 + width * 4)] = 0; // filter: none
    rgba.copy(raw, y * (1 + width * 4) + 1, y * width * 4, (y + 1) * width * 4);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;  // bit depth
  ihdr[9] = 6;  // color type RGBA
  ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 6 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

/* Tiny canvas helper: RGBA buffer with rect/circle/text drawing. */
class Canvas {
  constructor(w, h, bg = [18, 24, 20, 255]) {
    this.w = w; this.h = h;
    this.data = Buffer.alloc(w * h * 4);
    for (let i = 0; i < w * h; i++) {
      this.data[i * 4] = bg[0]; this.data[i * 4 + 1] = bg[1];
      this.data[i * 4 + 2] = bg[2]; this.data[i * 4 + 3] = bg[3];
    }
  }
  px(x, y, [r, g, b, a = 255]) {
    x |= 0; y |= 0;
    if (x < 0 || y < 0 || x >= this.w || y >= this.h) return;
    const i = (y * this.w + x) * 4;
    const ia = 255 - a;
    this.data[i] = (r * a + this.data[i] * ia) / 255 | 0;
    this.data[i + 1] = (g * a + this.data[i + 1] * ia) / 255 | 0;
    this.data[i + 2] = (b * a + this.data[i + 2] * ia) / 255 | 0;
    this.data[i + 3] = Math.max(this.data[i + 3], a);
  }
  rect(x, y, w, h, c) {
    for (let yy = y; yy < y + h; yy++) for (let xx = x; xx < x + w; xx++) this.px(xx, yy, c);
  }
  disc(cx, cy, rad, c) {
    for (let y = -rad; y <= rad; y++) {
      const span = Math.floor(Math.sqrt(rad * rad - y * y));
      for (let x = -span; x <= span; x++) this.px(cx + x, cy + y, c);
    }
  }
  ring(cx, cy, rad, thick, c) {
    const r2 = rad * rad, r2i = (rad - thick) * (rad - thick);
    for (let y = -rad; y <= rad; y++) for (let x = -rad; x <= rad; x++) {
      const d = x * x + y * y;
      if (d <= r2 && d >= r2i) this.px(cx + x, cy + y, c);
    }
  }
  text(x, y, str, scale, c) {
    let cx = x;
    for (const ch of String(str).toUpperCase()) {
      cx += this.glyph(cx, y, ch, scale, c);
    }
    return cx - x;
  }
  glyph(x, y, ch, scale, c) {
    const g = FONT[ch] || FONT['?'];
    const pitch = 6 * scale;
    if (!g) return pitch;
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 5; col++) {
        if (g[row] & (1 << (4 - col))) this.rect(x + col * scale, y + row * scale, scale, scale, c);
      }
    }
    return pitch;
  }
  measure(str, scale) { return String(str).length * 6 * scale; }
  textCenter(cx, y, str, scale, c) {
    const w = this.measure(str, scale);
    this.text(Math.round(cx - w / 2), y, str, scale, c);
  }
  widthOf(str, scale) { return this.measure(str, scale); }
  png() { return encodePNG(this.w, this.h, this.data); }
}

